"""Skip, with a stated reason, the tests that need inputs this repository does not ship.

Two kinds of input are kept out of git on purpose (see .gitignore):
  data/registry/**/*.nc   third-party ocean data (GEBCO bathymetry, CMEMS currents)
  runs/                   outputs generated by the pipelines (`make evidence`)

On a machine that has them, every test runs. On a fresh clone or in CI, the tests that need them are
reported as skipped with the missing path, instead of failing.
"""
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "data" / "registry"
HEADLINE_RUN = ROOT / "runs" / "phase3-headline" / "comparison.json"
CMEMS_FILES = list((REGISTRY / "cmems").glob("*.nc")) if (REGISTRY / "cmems").exists() else []

# Tests that fail with an assertion, not a missing-file error, when their input is absent.
NEEDS_GENERATED_RUNS = {"test_parse_summary_has_required_keys", "test_parse_headline_subkeys",
                        "test_parse_headline_values_match_frozen_evidence", "test_parse_runs_lists_all_run_dirs",
                        "test_server_integration"}
NEEDS_CMEMS = {"test_cmems_updates_config_velocity_and_currents", "test_extract_on_real_cmems_file",
               "test_build_with_real_cmems_passes_fd_cap"}


def pytest_collection_modifyitems(items):
    for item in items:
        if item.name in NEEDS_GENERATED_RUNS and not HEADLINE_RUN.exists():
            item.add_marker(pytest.mark.skip(reason="needs generated runs/ (run `make evidence` first)"))
        elif item.name in NEEDS_CMEMS and not CMEMS_FILES:
            item.add_marker(pytest.mark.skip(reason="needs CMEMS currents file under data/registry/cmems/ (not shipped)"))


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_call(item):
    """A missing file under data/registry/ means the external dataset is not installed: skip, do not fail."""
    outcome = yield
    if outcome.excinfo is None:
        return
    error = outcome.excinfo[1]
    missing = str(getattr(error, "filename", "") or "")
    if isinstance(error, FileNotFoundError) and "data/registry/" in missing:
        outcome.force_exception(pytest.skip.Exception(f"needs external data not shipped with the repo: {missing}"))
