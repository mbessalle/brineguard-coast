#!/usr/bin/env bash
# Deterministic session-start orientation brief (SSSF Tier 3 — zero LLM tokens).
# Run by the Claude Code SessionStart hook (startup+resume); stdout is injected
# into the orchestrator's context. Keep output bounded and factual.
set -u
cd "$(dirname "$0")/.." || exit 0

section() { printf '\n== %s ==\n' "$1"; }

printf 'SESSION BRIEF %s (generated by tools/session_brief.sh)\n' "$(date -u +%Y-%m-%dT%H:%MZ)"

section "Git"
printf 'branch: %s\n' "$(git rev-parse --abbrev-ref HEAD 2>/dev/null)"
git log --oneline -5 2>/dev/null
changed=$(git status --porcelain 2>/dev/null)
if [ -n "$changed" ]; then
  printf -- '--- uncommitted (%s files):\n%s\n' "$(printf '%s\n' "$changed" | wc -l)" "$changed"
else
  echo "worktree clean"
fi

section "Memory index"
memdir="$HOME/.claude/projects/$(pwd | tr '/' '-')/memory"
cat "$memdir/MEMORY.md" 2>/dev/null || echo "(no memory index at $memdir)"

section "Top-level docs"
ls -1t -- *.md 2>/dev/null | head -10
echo "(BUILD_PLAN.md is canonical; SSSF spec: adws/SSSF_SPEC.md; tier routing: sssf.config.yaml)"

section "Agent CLI presences"
for c in claude codex pi opencode gemini aider droid grok cursor; do
  v=$(command -v "$c" 2>/dev/null) && printf '%-9s %s\n' "$c" "$v"
done

section "Orca presences"
if timeout 8 orca status --json >/dev/null 2>&1; then
  timeout 8 orca terminal list --json 2>/dev/null | python3 -c "
import json,sys
try:
    d=json.load(sys.stdin)
    for t in d['result']['terminals']:
        wt=t['worktreePath'].split('/')[-1] or '(floating)'
        print(f\"{t['title'][:48]:48} | {wt[:30]:30} | {t['handle']}\")
except Exception as e:
    print(f'(terminal list unavailable: {e})')"
  echo "--- orchestration tasks:"
  timeout 8 orca orchestration task-list --brief --json 2>/dev/null | python3 -c "
import json,sys
try:
    d=json.load(sys.stdin)
    tasks=d.get('result',{}).get('tasks') or []
    for t in tasks[:15]:
        print(f\"{t.get('id','?')} [{t.get('status','?')}] {t.get('spec','')[:80]}\")
    if not tasks: print('(no orchestration tasks)')
except Exception as e:
    print(f'(task list unavailable: {e})')"
else
  echo "orca runtime unreachable (not in an Orca session, or app not running)"
fi

section "Model freshness"
timeout 20 python3 tools/model_freshness.py 2>/dev/null || echo "freshness check unavailable"

section "Standing orders"
echo "Role: SSSF orchestrator/evaluator (Tier 1). Delegate builds to Workhorse tier per sssf.config.yaml via 'orca orchestration' (task-create -> worker-start -> check --wait). Verify with deterministic gates (adws/gates.py, pytest). Do not implement feature code directly."
echo "VERIFY, DON'T GUESS: latest-model/version questions -> web-search 'latest model by <company>' first, then confirm in catalog/CLI. Never grep with guessed version substrings; list whole families."
