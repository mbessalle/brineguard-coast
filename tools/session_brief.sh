#!/usr/bin/env bash
# Deterministic session-start orientation brief (SSSF Tier 3 — zero LLM tokens).
# Run by the Claude Code SessionStart hook (startup+resume+compact); stdout is
# injected into the orchestrator's context. Keep output bounded and factual.
# Slow independent probes (model freshness, Orca lists) run concurrently.
set -u -o pipefail
cd "$(dirname "$0")/.." || exit 0

section() { printf '\n== %s ==\n' "$1"; }

# --- kick off slow independent probes in the background immediately ---------
tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT
{ timeout 20 python3 tools/model_freshness.py 2>/dev/null \
    || echo "freshness check unavailable"; } >"$tmpdir/fresh" &
fresh_pid=$!

orca_up=0
if timeout 8 orca status --json >/dev/null 2>&1; then
  orca_up=1
  timeout 8 orca terminal list --json 2>/dev/null >"$tmpdir/terms" &
  terms_pid=$!
  timeout 8 orca orchestration task-list --brief --json 2>/dev/null >"$tmpdir/tasks" &
  tasks_pid=$!
fi

printf 'SESSION BRIEF %s (generated by tools/session_brief.sh)\n' "$(date -u +%Y-%m-%dT%H:%MZ)"

section "Git"
branch=$(git rev-parse --abbrev-ref HEAD 2>/dev/null) || branch="(git unavailable)"
printf 'branch: %s\n' "$branch"
git log --oneline -5 2>/dev/null
if changed=$(git status --porcelain 2>/dev/null); then
  if [ -n "$changed" ]; then
    n=$(printf '%s\n' "$changed" | wc -l)
    printf -- '--- uncommitted (%s files, first 20):\n%s\n' "$n" "$(printf '%s\n' "$changed" | head -20)"
  else
    echo "worktree clean"
  fi
else
  echo "git status unavailable (do NOT assume clean)"
fi

section "Memory index"
memdir="$HOME/.claude/projects/$(pwd | tr '/' '-')/memory"
head -c 4000 "$memdir/MEMORY.md" 2>/dev/null || echo "(no memory index at $memdir)"

section "Top-level docs"
ls -1t -- *.md 2>/dev/null | head -10
echo "(BUILD_PLAN.md is canonical; SSSF spec: adws/SSSF_SPEC.md; tier routing: sssf.config.yaml)"

section "Agent CLI presences"
for c in claude codex pi opencode gemini aider droid grok cursor; do
  v=$(command -v "$c" 2>/dev/null) && printf '%-9s %s\n' "$c" "$v"
done

section "Orca presences"
if [ "$orca_up" = 1 ]; then
  wait "$terms_pid" 2>/dev/null
  python3 -c "
import json,sys
try:
    d=json.load(open('$tmpdir/terms'))
    for t in d['result']['terminals']:
        wt=t['worktreePath'].split('/')[-1] or '(floating)'
        print(f\"{t['title'][:48]:48} | {wt[:30]:30} | {t['handle']}\")
except Exception as e:
    print(f'(terminal list unavailable: {e})')"
  echo "--- orchestration tasks:"
  wait "$tasks_pid" 2>/dev/null
  python3 -c "
import json,sys
try:
    d=json.load(open('$tmpdir/tasks'))
    tasks=d.get('result',{}).get('tasks') or []
    for t in tasks[:15]:
        print(f\"{t.get('id','?')} [{t.get('status','?')}] {t.get('spec','')[:80]}\")
    if not tasks: print('(no orchestration tasks)')
except Exception as e:
    print(f'(task list unavailable: {e})')"
  ledger="adw_data/dispatch_ledger.jsonl"
  if [ -f "$ledger" ]; then
    echo "--- recent dispatches (ledger, last 5):"
    tail -5 "$ledger"
  fi
else
  echo "orca runtime unreachable (not in an Orca session, or app not running)"
fi

section "Model freshness"
wait "$fresh_pid" 2>/dev/null
cat "$tmpdir/fresh"

section "Standing orders"
echo "Role: SSSF orchestrator/evaluator (Tier 1). Delegate builds to Workhorse tier per sssf.config.yaml via tools/orca_dispatch.py run --route <r> --spec @file --wait (wraps task-create -> worker-start/dispatch -> check --wait -> ack). Verify with deterministic gates (adws/gates.py, pytest). Do not implement feature code directly."
echo "VERIFY, DON'T GUESS: latest-model/version questions -> web-search 'latest model by <company>' first, then confirm in catalog/CLI. Never grep with guessed version substrings; list whole families."
echo "PRECEDENCE: evidence integrity > task contract > gates > scope > latency; degrade to PARTIAL/UNVERIFIED loudly, never silently. Review labels: thinking-low = WORDING-CHECK only; FINAL/agreed requires an adversarial medium+ pass. Retrieval budget: <30s, <3k tokens, one targeted command. Log every agent call: tools/agent_io_log.sh -> agent-io branch."
echo "PLAYBOOKS (LLM-interpreted recovery pseudo-code, adws/playbooks/): dispatch_recovery.md + verification_feedback.md (warm-fix loop; waiter_exists, selector_not_found, silent worker_done, CLI updater, terminal-wait, handoff mismatch), escalation_triage.md (worker questions: scout-first). Spec authoring: adws/templates/spec_template.md. Boundary: code verifies, playbooks recover, templates carry intent."
